#!/usr/bin/env python3
"""Multi-backend replay of already-logged condition-S rows — with NO model calls.

Every condition-S row in results/runs_*.jsonl carries the query `plan` the model produced.
Compiling and executing that plan is deterministic, so the entire S arm can be re-run
against a DIFFERENT execution backend without spending a single token: the model's
contribution (the plan) is frozen, and only the layer underneath it changes. That is the
mechanism behind the project's cross-backend agreement result — if the same stored plans
produce the same answers on DuckDB, on BigQuery and through Looker, then the semantic
contract, not the warehouse, is what is doing the work.

How this differs from harness/recompile_s.py (which it generalises):
  * recompile_s.py REWRITES its input files in place. replay_s.py never touches an input
    file; it always writes a new --out file, and refuses to write over an input.
  * recompile_s.py is hard-wired to compile.py + DuckDB. replay_s.py dispatches through a
    Backend interface (duckdb and bq implemented and executed against live warehouses;
    looker is still a documented stub).
  * recompile_s.py imports harness/run.py, which imports harness/llm.py, which reads
    GEMINI_API_KEY at import time. replay_s.py depends only on compiler/compile.py, so it
    runs with no model credentials of any kind.

WHY THERE IS NO NEW CONDITION CODE
A replayed row keeps condition "S" and records where it ran in a new `backend` field
(default "compiler-duckdb"). Introducing e.g. "S_bq" would fork every downstream
aggregation: CONDS = ["U","D","G","S"] is hard-coded in score/stats.py:15,
score/plots.py:23 and in ~10 places in score/extract_numbers.py. Backend is a second
axis, orthogonal to the grounding ladder; it does not belong on the condition axis.

USAGE
  # replay the stored plans through the DuckDB compiler into a NEW file
  harness/replay_s.py --backend duckdb --in 'results/runs_*.jsonl' --out results/replay_duckdb.jsonl

  # the same frozen plans, compiled through BigQueryDialect and executed on BigQuery
  harness/replay_s.py --backend bq     --in 'results/runs_*.jsonl' --out results/replay_bq.jsonl

  # compare two replay outputs (or a replay output against the original runs file)
  harness/replay_s.py --agreement results/replay_duckdb.jsonl results/replay_bq.jsonl

  # ...as CSV too
  harness/replay_s.py --agreement A.jsonl B.jsonl --agreement-csv /tmp/agreement.csv

The agreement matrix these produce, with its triage and its caveats, is generated by
scripts/agreement_matrix.py -> results/AGREEMENT-duckdb-vs-bq.md. Its negative control is
scripts/mutation_check.py; the data-parity check underneath it is
scripts/warehouse_parity.py.
"""
