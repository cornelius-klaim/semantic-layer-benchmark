def replay_row(row: dict, backend: Backend, models_dir: Optional[str] = None) -> dict:
    """Return a NEW row dict; never mutates `row`.

    `replay_status` records what actually happened:
      executed          - the backend compiled and ran (or refused) the stored plan
      no_plan           - the logged row has no usable plan (a model-side failure such as
                          `unparseable_plan`); nothing for a backend to do, outcome kept
      passthrough_non_s - a non-S row copied verbatim (only with --include-non-s)
    """
    out = dict(row)
    if row.get("condition") != "S":
        out["backend"] = row.get("backend", DEFAULT_BACKEND)
        out["replay_status"] = "passthrough_non_s"
        return out
    out["backend"] = backend.id
    plan = row.get("plan")
    if not isinstance(plan, dict):
        out["replay_status"] = "no_plan"
        return out
    model = load_semantic_model(row["dataset"], models_dir)
    res = backend.execute(model, plan)
    out["sql"] = res.get("sql")
    out["rows"] = res.get("rows")
    out["outcome"] = res["outcome"]
    out["detail"] = res.get("detail")
    out["replay_status"] = "executed"
    return out


def read_jsonl(path: str) -> List[dict]:
    rows = []
    with open(path) as fh:
        for ln, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise SystemExit(f"{path}:{ln}: bad JSON ({e})")
    return rows


def expand_inputs(patterns: Sequence[str]) -> List[str]:
    """Accept both shell-expanded paths and unexpanded globs."""
    files: List[str] = []
    for pat in patterns:
        if any(ch in pat for ch in "*?["):
            hits = sorted(glob.glob(pat))
            if not hits:
                raise SystemExit(f"--in pattern matched nothing: {pat}")
            files.extend(hits)
        else:
            if not os.path.exists(pat):
                raise SystemExit(f"--in file not found: {pat}")
            files.append(pat)
    seen, uniq = set(), []
    for f in files:
        a = os.path.abspath(f)
        if a not in seen:
            seen.add(a)
            uniq.append(f)
    return uniq


def cmd_replay(a: argparse.Namespace) -> int:
    files = expand_inputs(a.inp)
    out_abs = os.path.abspath(a.out)
    if out_abs in {os.path.abspath(f) for f in files}:
        raise SystemExit("--out must not be one of the --in files: replay_s.py never rewrites inputs")
    if fnmatch.fnmatch(os.path.basename(out_abs), "runs_*.jsonl") and not a.allow_runs_name:
        raise SystemExit(
            f"refusing to write '{os.path.basename(out_abs)}': score/score.py globs "
            "results/runs_*.jsonl, so a replay file with that name would be double-counted "
            "into the headline aggregates. Rename it (e.g. replay_<backend>.jsonl) or pass "
            "--allow-runs-name if you really mean it."
        )
    os.makedirs(os.path.dirname(out_abs) or ".", exist_ok=True)

    kw: Dict[str, Any] = {}
    if a.backend == "duckdb" and a.warehouse_dir:
        kw["warehouse_dir"] = a.warehouse_dir
    if a.backend == "bq":
        if a.bq_project:
            kw["project"] = a.bq_project
        if a.bq_dataset:
            m = {}
            for pair in a.bq_dataset:
                if "=" not in pair:
                    raise SystemExit(f"--bq-dataset expects ds=bq_dataset_id, got {pair!r}")
                k, v = pair.split("=", 1)
                m[k.strip()] = v.strip()
            kw["dataset_map"] = m
        if a.bq_location:
            kw["location"] = a.bq_location
        if a.no_utc_check:
            kw["verify_utc"] = False
    backend = make_backend(a.backend, **kw)
    status = Counter()
    outcomes = Counter()
    written = 0
    ok = False
    try:
        with open(out_abs, "w") as fout:
            for f in files:
                rows = read_jsonl(f)
                n_s = 0
                for r in rows:
                    is_s = r.get("condition") == "S"
                    if not is_s and not a.include_non_s:
                        status["skipped_non_s"] += 1
                        continue
                    if is_s and a.limit and n_s >= a.limit:
                        status["skipped_over_limit"] += 1
                        continue
                    new = replay_row(r, backend, a.models_dir)
                    if is_s:
                        n_s += 1
                        outcomes[new.get("outcome")] += 1
                    status[new["replay_status"]] += 1
                    fout.write(json.dumps(new, default=str) + "\n")
                    written += 1
                print(f"  {os.path.basename(f):32} rows={len(rows):5} S={n_s:5}", flush=True)
        ok = True
    finally:
        backend.close()
        if not ok:
            # a half-written replay file must never be left behind: it would look like a
            # complete run to the agreement report and silently understate coverage.
            try:
                os.remove(out_abs)
                print(f"replay failed — removed incomplete {out_abs}", file=sys.stderr)
            except OSError:
                pass

    print(f"\nbackend : {backend.id}")
    print(f"wrote   : {written} rows -> {out_abs}")
    print(f"status  : {dict(status)}")
    print(f"outcomes(S): {dict(outcomes)}")
    if isinstance(backend, BigQueryBackend):
        print(f"bigquery: {backend.queries_run} distinct statements executed, "
              f"{backend.cache_hits} cache hits, "
              f"{backend.bytes_billed / 1e9:.3f} GB billed")
    return 0


# ======================================================================================
# agreement report
# ======================================================================================
# A timestamp/date cell as `json.dumps(..., default=str)` renders it. Four shapes occur
# across the two arms: "2024-05-01" (a BigQuery DATE), "2024-05-01 00:00:00" (a DuckDB
# naive TIMESTAMP), "2024-05-01 00:00:00+00:00" (a BigQuery TIMESTAMP, which the client
# always hands back tz-aware) and the ISO "T" separator.
_TEMPORAL_RE = re.compile(
    r"^(?P<y>\d{4})-(?P<mo>\d{2})-(?P<d>\d{2})"
    r"(?:[ T](?P<h>\d{2}):(?P<mi>\d{2})(?::(?P<s>\d{2})(?:\.(?P<us>\d{1,6}))?)?)?"
    r"\s*(?P<tz>Z|[+-]\d{2}:?\d{2})?$"
)

# how a cell had to be normalised before it would compare equal — diagnostics only, never
# part of the equality key, so the report can say exactly what it forgave and how often
REPR_KINDS = ("numeric_string", "date_only", "tz_aware", "naive_timestamp")


def _parse_temporal(s: str) -> Optional[Tuple[float, str]]:
    """'2024-05-01[ 00:00:00[+00:00]]' -> (epoch_seconds_utc, repr_kind), else None.

    A bare date is read as midnight; an absent zone is read as UTC. Both readings are
    forced by the comparison this module exists to make: DuckDB stores a naive TIMESTAMP
    that the loader mapped onto a UTC instant in BigQuery, so "no zone" MEANS UTC here.
    That is an assumption about how the two warehouses were loaded, not a general truth —
    it is what BigQueryBackend._verify_utc checks at connect time.
    """
    m = _TEMPORAL_RE.match(s.strip())
    if not m:
        return None
    g = m.groupdict()
    try:
        dt = datetime.datetime(
            int(g["y"]), int(g["mo"]), int(g["d"]),
            int(g["h"] or 0), int(g["mi"] or 0), int(g["s"] or 0),
            int((g["us"] or "0").ljust(6, "0")),
            tzinfo=datetime.timezone.utc,
        )
    except ValueError:
        return None
    off = g["tz"]
    if off and off != "Z":
        sign = 1 if off[0] == "+" else -1
        body = off[1:].replace(":", "")
        dt -= datetime.timedelta(minutes=sign * (int(body[:2]) * 60 + int(body[2:] or 0)))
    kind = "tz_aware" if off else ("naive_timestamp" if g["h"] is not None else "date_only")
    return dt.timestamp(), kind


def _canon_cell(v: Any) -> Tuple[Tuple[str, Any], Optional[str]]:
    """Canonicalise one result cell -> (equality_key, repr_kind_or_None).

    JSONL rows were written with `json.dumps(row, default=str)`, so anything that is not a
    JSON scalar arrives as a string. Two normalisations are applied, and BOTH are counted
    into the agreement matrix rather than silently absorbed:

      * numeric  — "123.45" (a Decimal, or any number stringified by `default=str`)
        canonicalises to the float 123.45, so a money column is not a divergence purely
        because one engine's client returned a different Python type.
      * temporal — a DATE, a naive TIMESTAMP and a UTC-aware TIMESTAMP denoting the same
        instant canonicalise to the same instant. This one matters: BigQuery's client
        always returns TIMESTAMP tz-aware ("...+00:00") while DuckDB returns it naive, so
        WITHOUT this every grouped-by-month result would read as divergent for a reason
        that has nothing to do with the semantic layer.

    `repr_kind` is diagnostic only. It never participates in equality; it exists so the
    report can state how many cells needed which normalisation instead of asserting a
    clean sweep it has quietly manufactured.
    """
    if isinstance(v, bool):
        return ("b", v), None
    if isinstance(v, (int, float)):
        f = float(v)
        return (("nan", None) if math.isnan(f) else ("n", f)), None
    if v is None:
        return ("null", None), None
    s = str(v)
    if _NUMERIC_RE.match(s.strip()):
        return ("n", float(s)), "numeric_string"
    t = _parse_temporal(s)
    if t is not None:
        return ("t", t[0]), t[1]
    return ("s", s), None


def _canon_rows(rows: Any) -> Tuple[Optional[List[Tuple[Tuple[str, Any], ...]]], Counter]:
    """(canonical rows, Counter of repr kinds seen). rows=None -> (None, empty counter)."""
    kinds: Counter = Counter()
    if rows is None:
        return None, kinds
    out = []
    for r in rows:
        cells = r if isinstance(r, (list, tuple)) else [r]
        keys = []
        for v in cells:
            k, rk = _canon_cell(v)
            keys.append(k)
            if rk:
                kinds[rk] += 1
        out.append(tuple(keys))
    return out, kinds


def _cells_close(a: Tuple[str, Any], b: Tuple[str, Any], tol: float) -> bool:
    if a[0] != b[0]:
        return False
    if a[0] == "n":
        x, y = a[1], b[1]
        if abs(y) < 1e-9:
            return abs(x) < 1e-6
        return abs(x - y) / abs(y) <= tol
    return a[1] == b[1]


def match_rows(A: List[tuple], B: List[tuple], tol: float) -> Optional[List[int]]:
    """Order-insensitive match within a relative tolerance.

    Returns the index in B paired with each row of A, or None if no complete pairing
    exists. Order-insensitive because two backends may break ties differently on an
    ORDER BY with equal keys, and because a SELECT without an ORDER BY denotes a set;
    greedy matching, as in score/score.py:topn_match, which is exact for the result shapes
    in this benchmark (no row is ambiguous between two partners at these tolerances).

    Returning the pairing rather than a bool is what lets the caller report whether the
    two sides agreed in the SAME ORDER, instead of guessing.
    """
    if len(A) != len(B):
        return None
    used = [False] * len(B)
    pairing: List[int] = []
    for ra in A:
        hit = None
        for i, rb in enumerate(B):
            if used[i]:
                continue
            if len(ra) == len(rb) and all(_cells_close(x, y, tol) for x, y in zip(ra, rb)):
                hit = i
                break
        if hit is None:
            return None
        used[hit] = True
        pairing.append(hit)
    return pairing


def rows_within_tol(A: List[tuple], B: List[tuple], tol: float) -> bool:
    """Back-compatible boolean form of match_rows()."""
    return match_rows(A, B, tol) is not None


# ordered least -> most severe; a question's verdict is the most severe class it contains
SEVERITY = ["identical", "within_tol", "both_refused", "both_error",
            "missing_in_one", "error_by_one", "refused_by_one", "divergent"]
AGREE_CLASSES = {"identical", "within_tol", "both_refused", "both_error"}


def classify_pair(ra: dict, rb: dict, tol: float = DEFAULT_TOL) -> Tuple[str, Dict[str, Any]]:
    """-> (class, diagnostics).

    class is one of: identical | within_tol | divergent | refused_by_one | both_refused |
    both_error | error_by_one.

    "identical" means every cell is EXACTLY equal after representation canonicalisation
    (see _canon_cell) — no tolerance is spent. It is judged ORDER-INSENSITIVELY, matching
    score/score.py:topn_match: a SELECT with no ORDER BY denotes a set, row order out of a
    FULL OUTER JOIN is not deterministic even within DuckDB (compiler/README-dialects.md
    documents ~845/1040 order-stability under the SAME engine), and BigQuery is a
    distributed shuffle. Ordering is therefore reported as a diagnostic
    (`order_differs`), not as disagreement about the answer.

    "within_tol" is strictly weaker: at least one numeric cell needed the relative
    tolerance to match. Keeping the two apart is the whole point — collapsing them would
    hide float drift behind the same headline as an exact match.

    diagnostics: {"repr": {kind: count}, "order_differs": bool, "nrows": int,
                  "max_rel_err": float|None}
    """
    d: Dict[str, Any] = {"repr": {}, "order_differs": False, "nrows": None,
                         "max_rel_err": None, "refusal_text_differs": None}
    oa, ob = ra.get("outcome"), rb.get("outcome")
    if oa == "refusal" or ob == "refusal":
        if oa == ob:
            # both refused — but a refusal is a governance decision, so the REASON has to
            # match too. Two arms refusing the same question for different reasons is not
            # agreement, it is a coincidence, and it must not be reported as agreement.
            d["refusal_text_differs"] = str(ra.get("detail")) != str(rb.get("detail"))
            return "both_refused", d
        return "refused_by_one", d
    if oa == "error" or ob == "error":
        return ("both_error" if oa == ob else "error_by_one"), d
    A, ka = _canon_rows(ra.get("rows"))
    B, kb = _canon_rows(rb.get("rows"))
    d["repr"] = dict(ka + kb)
    if A is None or B is None:
        return "divergent", d
    d["nrows"] = len(A)
    exact = match_rows(A, B, 0.0)
    if exact is not None:
        d["order_differs"] = exact != list(range(len(A)))
        return "identical", d
    pairing = match_rows(A, B, tol)
    if pairing is not None:
        d["order_differs"] = pairing != list(range(len(A)))
        d["max_rel_err"] = _max_rel_err(A, B, pairing)
        return "within_tol", d
    return "divergent", d


def _max_rel_err(A: List[tuple], B: List[tuple], pairing: List[int]) -> Optional[float]:
    """Largest relative gap over the pairing that made A and B match."""
    worst = None
    for ra, j in zip(A, pairing):
        for x, y in zip(ra, B[j]):
            if x[0] == "n" and y[0] == "n" and abs(y[1]) >= 1e-9:
                e = abs(x[1] - y[1]) / abs(y[1])
                worst = e if worst is None else max(worst, e)
    return worst


def _key(r: dict) -> Tuple:
    return (r.get("qid"), r.get("condition"), r.get("model"), r.get("run"))


def _index(rows: Iterable[dict]) -> Tuple[Dict[Tuple, dict], int]:
    idx: Dict[Tuple, dict] = {}
    dupes = 0
    for r in rows:
        k = _key(r)
        if k in idx:
            dupes += 1
        idx[k] = r
    return idx, dupes


def agreement_report(path_a: str, path_b: str, tol: float = DEFAULT_TOL,
                     conditions: Sequence[str] = ("S",)) -> Dict[str, Any]:
    """Compare two replay outputs run-for-run and roll the result up per question.

    Rows are paired on (qid, condition, model, run) — the identity of a single logged
    attempt — and each pair is classified. The per-question verdict is the most severe
    class among that question's pairs.
    """
    A = [r for r in read_jsonl(path_a) if r.get("condition") in conditions]
    B = [r for r in read_jsonl(path_b) if r.get("condition") in conditions]
    ia, dup_a = _index(A)
    ib, dup_b = _index(B)

    per_q: "OrderedDict[str, Counter]" = OrderedDict()
    detail: List[dict] = []
    repr_kinds: Counter = Counter()
    order_diffs = 0
    worst_rel: Optional[float] = None
    for k in list(ia.keys()) + [k for k in ib.keys() if k not in ia]:
        qid = k[0]
        per_q.setdefault(qid, Counter())
        ra, rb = ia.get(k), ib.get(k)
        if ra is None or rb is None:
            cls, dg = "missing_in_one", {"repr": {}, "order_differs": False,
                                         "nrows": None, "max_rel_err": None}
        else:
            cls, dg = classify_pair(ra, rb, tol)
        per_q[qid][cls] += 1
        repr_kinds.update(dg["repr"])
        order_diffs += int(bool(dg["order_differs"]))
        if dg["max_rel_err"] is not None:
            worst_rel = dg["max_rel_err"] if worst_rel is None else max(worst_rel, dg["max_rel_err"])
        detail.append({"qid": qid, "condition": k[1], "model": k[2], "run": k[3], "cls": cls,
                       "outcome_a": (ra or {}).get("outcome"), "outcome_b": (rb or {}).get("outcome"),
                       "detail_a": (ra or {}).get("detail"), "detail_b": (rb or {}).get("detail"),
                       "dataset": (ra or rb or {}).get("dataset"),
                       "order_differs": dg["order_differs"], "nrows": dg["nrows"],
                       "max_rel_err": dg["max_rel_err"]})

    totals = Counter()
    for c in per_q.values():
        totals.update(c)
    return {
        "path_a": path_a, "path_b": path_b, "tol": tol,
        "backend_a": sorted({r.get("backend", DEFAULT_BACKEND) for r in A}) or ["?"],
        "backend_b": sorted({r.get("backend", DEFAULT_BACKEND) for r in B}) or ["?"],
        "n_a": len(A), "n_b": len(B), "dupes_a": dup_a, "dupes_b": dup_b,
        "per_question": per_q, "totals": totals, "pairs": detail,
        "repr_kinds": dict(repr_kinds), "order_differs": order_diffs,
        "max_rel_err": worst_rel,
    }


def print_agreement(rep: Dict[str, Any], show: int = 20) -> None:
    tot = rep["totals"]
    n = sum(tot.values())
    print("=== Cross-backend agreement ===")
    print(f"A: {rep['path_a']}   backend={','.join(rep['backend_a'])}  rows={rep['n_a']}"
          + (f"  (WARNING: {rep['dupes_a']} duplicate keys)" if rep["dupes_a"] else ""))
    print(f"B: {rep['path_b']}   backend={','.join(rep['backend_b'])}  rows={rep['n_b']}"
          + (f"  (WARNING: {rep['dupes_b']} duplicate keys)" if rep["dupes_b"] else ""))
    print(f"tolerance: {rep['tol'] * 100:g}% relative;  pairs compared: {n}\n")

    hdr = f"{'qid':28} {'n':>4} {'ident':>6} {'tol':>4} {'diverg':>7} {'ref1':>5} {'other':>6}  verdict"
    print(hdr)
    print("-" * len(hdr))
    for qid, c in rep["per_question"].items():
        other = sum(v for k, v in c.items() if k not in ("identical", "within_tol", "divergent", "refused_by_one"))
        verdict = max(c, key=lambda k: SEVERITY.index(k) if k in SEVERITY else 99)
        print(f"{qid[:28]:28} {sum(c.values()):>4} {c['identical']:>6} {c['within_tol']:>4} "
              f"{c['divergent']:>7} {c['refused_by_one']:>5} {other:>6}  {verdict}")
    print("-" * len(hdr))
    print(f"{'TOTAL':28} {n:>4} {tot['identical']:>6} {tot['within_tol']:>4} "
          f"{tot['divergent']:>7} {tot['refused_by_one']:>5} "
          f"{sum(v for k, v in tot.items() if k not in ('identical','within_tol','divergent','refused_by_one')):>6}")
    print("\nclass counts:", dict(tot))
    agree = sum(v for k, v in tot.items() if k in AGREE_CLASSES)
    if n:
        print(f"agreement (identical + within tolerance + both refused/errored): "
              f"{agree}/{n} = {100.0 * agree / n:.2f}%")
        print(f"  of which exactly equal (no tolerance spent): "
              f"{tot['identical']}/{n} = {100.0 * tot['identical'] / n:.2f}%")
    print(f"\nrepresentation normalisations applied (cells): {rep.get('repr_kinds') or '{}'}")
    print(f"pairs whose rows matched only after reordering: {rep.get('order_differs', 0)}")
    if rep.get("max_rel_err") is not None:
        print(f"largest relative gap inside the tolerance:      {rep['max_rel_err']:.3e}")

    bad = [d for d in rep["pairs"] if d["cls"] not in AGREE_CLASSES]
    if bad:
        print(f"\n--- non-agreeing pairs ({len(bad)}; showing up to {show}) ---")
        for d in bad[:show]:
            print(f"  {d['cls']:15} {d['qid']:22} {d['model']} run={d['run']} "
                  f"A={d['outcome_a']} B={d['outcome_b']}")
            if d["detail_a"] or d["detail_b"]:
                print(f"      A.detail={str(d['detail_a'])[:110]}")
                print(f"      B.detail={str(d['detail_b'])[:110]}")


def write_agreement_csv(rep: Dict[str, Any], path: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    with open(path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["qid", "n", "identical", "within_tol", "divergent", "refused_by_one",
                    "both_refused", "both_error", "error_by_one", "missing_in_one", "verdict"])
        for qid, c in rep["per_question"].items():
            verdict = max(c, key=lambda k: SEVERITY.index(k) if k in SEVERITY else 99)
            w.writerow([qid, sum(c.values()), c["identical"], c["within_tol"], c["divergent"],
                        c["refused_by_one"], c["both_refused"], c["both_error"],
                        c["error_by_one"], c["missing_in_one"], verdict])
    print(f"\nwrote per-question agreement CSV -> {path}")


