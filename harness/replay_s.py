def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        prog="replay_s.py",
        description="Replay logged condition-S plans through a selectable backend (no model calls), "
                    "or report agreement between two replay outputs.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="replay_s.py NEVER modifies an input file (unlike harness/recompile_s.py, which "
               "rewrites in place).",
    )
    ap.add_argument("--backend", choices=sorted(BACKENDS), help="execution backend for the replay")
    ap.add_argument("--in", dest="inp", nargs="+", metavar="JSONL",
                    help="logged run files to replay (shell globs fine)")
    ap.add_argument("--out", metavar="JSONL", help="new JSONL file to write (must not be an input)")
    ap.add_argument("--include-non-s", action="store_true",
                    help="also copy non-S rows through verbatim (default: S rows only)")
    ap.add_argument("--limit", type=int, default=0, help="replay at most N S-rows per input file (smoke test)")
    ap.add_argument("--models-dir", default=None, help="override semantic_models/ directory")
    ap.add_argument("--warehouse-dir", default=None, help="override warehouse/ directory (duckdb backend)")
    ap.add_argument("--bq-project", default=None, metavar="ID",
                    help=f"BigQuery project (default {BigQueryBackend.DEFAULT_PROJECT}, or $BQ_PROJECT)")
    ap.add_argument("--bq-dataset", action="append", default=None, metavar="ds=bq_dataset_id",
                    help="map a benchmark dataset to a BigQuery dataset; repeatable "
                         f"(default {BigQueryBackend.DEFAULT_DATASET_MAP})")
    ap.add_argument("--bq-location", default=None, metavar="LOC", help="BigQuery job location")
    ap.add_argument("--no-utc-check", action="store_true",
                    help="skip the connect-time UTC assertion (NOT recommended: a zone shift "
                         "silently rebuckets month/year rows instead of raising)")
    ap.add_argument("--allow-runs-name", action="store_true",
                    help="permit an --out named runs_*.jsonl (score/score.py would glob it)")
    ap.add_argument("--agreement", nargs=2, metavar=("A.jsonl", "B.jsonl"),
                    help="compare two replay outputs instead of replaying")
    ap.add_argument("--agreement-csv", default=None, metavar="CSV",
                    help="also write the per-question agreement table as CSV")
    ap.add_argument("--tolerance", type=float, default=DEFAULT_TOL,
                    help=f"relative tolerance for the agreement report (default {DEFAULT_TOL})")
    ap.add_argument("--show", type=int, default=20, help="how many non-agreeing pairs to print")
    a = ap.parse_args(argv)

    if a.agreement:
        rep = agreement_report(a.agreement[0], a.agreement[1], a.tolerance)
        print_agreement(rep, a.show)
        if a.agreement_csv:
            write_agreement_csv(rep, a.agreement_csv)
        return 0

    missing = [n for n, v in (("--backend", a.backend), ("--in", a.inp), ("--out", a.out)) if not v]
    if missing:
        ap.error("missing required argument(s): " + ", ".join(missing) + " (or use --agreement A B)")
    return cmd_replay(a)


if __name__ == "__main__":
    sys.exit(main())
