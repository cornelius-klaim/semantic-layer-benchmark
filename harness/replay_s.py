_MODEL_CACHE: Dict[Tuple[str, str], dict] = {}


def load_semantic_model(dataset: str, models_dir: Optional[str] = None) -> dict:
    """Load and cache semantic_models/<dataset>.yaml."""
    d = models_dir or _p("semantic_models")
    key = (os.path.abspath(d), dataset)
    if key not in _MODEL_CACHE:
        m = C.load_model(os.path.join(d, f"{dataset}.yaml"))
        m.setdefault("dataset", dataset)  # every shipped model already declares it
        _MODEL_CACHE[key] = m
    return _MODEL_CACHE[key]


