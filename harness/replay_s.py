# Backend interface
# ======================================================================================
class Backend:
    """Executes an already-produced query plan against one warehouse or query service.

    CONTRACT.  execute(semantic_model, plan) returns a dict with exactly these keys:

        rows     list of result rows (each a list/tuple of scalars), or None
        sql      the SQL the layer generated, or None when no SQL was produced
        outcome  "ok" | "refusal" | "error"   (harness/run.py's existing vocabulary)
        detail   refusal reason or error message; None when outcome == "ok"

    The dataset to run against is read from semantic_model["dataset"] — a plan is only
    ever meaningful relative to the model it was written against, so the pair is the
    whole input. Rules every backend must honour so that two backends are comparable:

      * A plan carrying a truthy "refuse" key is a MODEL refusal. Return
        outcome="refusal", sql=None, rows=None, detail=<the refuse value>, WITHOUT
        touching the warehouse. This keeps model refusals backend-independent by
        construction, so the agreement report can never report one as a divergence.
      * A plan the layer rejects (unknown field, grain violation, ...) is a LAYER
        refusal, and takes the same shape. compiler/compile.py:compile_plan already
        emits both kinds, so any SQL-generating backend gets this for free.
      * outcome="error" is reserved for a genuine execution failure. Keep `sql` populated
        in that case so the failing statement stays auditable.
      * Never mutate `plan` or `semantic_model`.
    """

    id = "abstract"

    def execute(self, semantic_model: dict, plan: dict) -> Dict[str, Any]:
        raise NotImplementedError

    def close(self) -> None:  # pragma: no cover - trivial
        pass


class DuckDBBackend(Backend):
    """The reference backend: compiler/compile.py -> DuckDB dialect SQL -> warehouse/<ds>.duckdb.

    This is the backend that produced every committed condition-S row, so replaying a
    logged plan through it must reproduce that row exactly. The acceptance test for this
    module is precisely that round trip.
    """

    id = DEFAULT_BACKEND

    def __init__(self, warehouse_dir: Optional[str] = None) -> None:
        self.warehouse_dir = warehouse_dir or _p("warehouse")
        self._cons: Dict[str, Any] = {}

    def _con(self, dataset: str):
        if dataset not in self._cons:
            import duckdb  # imported lazily so --backend looker needs no duckdb

            path = os.path.join(self.warehouse_dir, f"{dataset}.duckdb")
            if not os.path.exists(path):
                raise FileNotFoundError(f"no warehouse for dataset '{dataset}': {path}")
            self._cons[dataset] = duckdb.connect(path, read_only=True)
        return self._cons[dataset]

    def execute(self, semantic_model: dict, plan: dict) -> Dict[str, Any]:
        comp = C.compile_plan(semantic_model, plan)
        if "refuse" in comp:
            # covers both the model refusal ({"refuse": ...}) and the layer refusal
            return {"rows": None, "sql": None, "outcome": "refusal", "detail": comp["refuse"]}
        sql = comp["sql"]
        try:
            rows = self._con(semantic_model["dataset"]).execute(sql).fetchall()
        except Exception as e:  # noqa: BLE001 — mirrors run.py:exec_sql
            return {"rows": None, "sql": sql, "outcome": "error", "detail": str(e)[:300]}
        return {"rows": rows, "sql": sql, "outcome": "ok", "detail": None}

    def close(self) -> None:
        for con in self._cons.values():
            try:
                con.close()
            except Exception:  # noqa: BLE001
                pass
        self._cons.clear()


class BigQueryBackend(Backend):
    """The dialect control arm: same plan, same semantic model, BigQuery-dialect SQL.

    SQL generation is NOT re-implemented here. compile_plan decides WHAT to emit — one
    subquery per measure at its own base grain, combined on the shared dimensions, ratios
    computed in the outer SELECT, which is the part that carries the fan-out guarantee —
    and compiler/dialects.py:BigQueryDialect decides how that is spelled. The compile step
    is therefore one call, and any structural difference between this arm and the DuckDB
    arm would be a bug in the dialect, not a feature of this backend.

    THE UTC CAVEAT (load-bearing; the whole comparison turns on it)
    --------------------------------------------------------------
    DuckDB stores a naive TIMESTAMP; BigQuery's TIMESTAMP is an absolute instant. The two
    warehouses hold the same instants (verified column-by-column at load time), but every
    operation that maps an instant onto a CALENDAR is zone-sensitive, and this benchmark
    has two of them: `TIMESTAMP_TRUNC(order_ts, MONTH)` and `DATE(order_ts)` inside the
    fiscal-year expression. Both default to UTC in BigQuery, which is the interpretation
    that reproduces DuckDB's naive arithmetic — so the correct behaviour is the default
    and this backend's job is only to make sure nothing perturbs it:

      * it never passes a `time_zone` argument to a *_TRUNC or DATE() call (the dialect
        emits none), so the server-side default of UTC stands;
      * it pins the *process* timezone to UTC before any datetime is rendered, so a cell
        serialised by `json.dumps(..., default=str)` cannot pick up the operator's local
        zone from `astimezone()`-style formatting anywhere downstream;
      * it asserts the two properties at connect time (see `_verify_utc`), because a
        silent zone shift would not raise — it would quietly move a row from one month
        bucket to the next and be indistinguishable from a real disagreement.

    RESULT SHAPE
    ------------
    Rows come back as positional tuples in SELECT order, so they compare directly against
    the DuckDB backend's `fetchall()`. Every column in both warehouses is FLOAT64/INT64/
    STRING/BOOL/TIMESTAMP (there is no NUMERIC anywhere), so no Decimal appears; float
    aggregates can still differ in the last bits because the two engines sum in different
    orders, which is what the agreement report's relative tolerance is for.

    ERRORS vs REFUSALS
    ------------------
    compile_plan lets DialectError propagate on purpose: a construct the dialect cannot
    spell is a gap in our coverage of the WAREHOUSE, not a governance decision about the
    QUESTION. It is caught here and reported as outcome="error" with a `dialect_gap:`
    prefix — never as a refusal, which would score as the semantic layer correctly
    declining and would let a translation gap flatter the headline result.

    CACHING
    -------
    The 1190 stored plans collapse to a much smaller set of distinct statements. Identical
    SQL is executed once and reused (`cache_hits` reports how often). This adds no
    determinism that BigQuery does not already provide — its own query cache returns the
    same materialised result for a repeated statement — but it does mean row ORDER is
    identical across repeats by construction, so the agreement report treats row order as
    a diagnostic and matches rows order-insensitively (as score/score.py:topn_match does).
    """

    id = "compiler-bigquery"

    # The DuckDB file `warehouse/<ds>.duckdb` and the BigQuery dataset holding the same
    # seeded rows. Table names inside are UNPREFIXED on purpose: BigQuery's implicit alias
    # for `project.dataset.orders` is `orders`, which is what keeps every "orders.column"
    # reference in the semantic model valid without touching the model.
    DEFAULT_DATASET_MAP = {"d1": "semantic_bench_d1", "d2": "semantic_bench_d2"}
    DEFAULT_PROJECT = os.environ.get("SEMBENCH_BQ_PROJECT", "")   # set this, or pass --project

    def __init__(self, project: Optional[str] = None, dataset_map: Optional[Dict[str, str]] = None,
                 location: Optional[str] = None, verify_utc: bool = True) -> None:
        self.project = project or os.environ.get("BQ_PROJECT") or self.DEFAULT_PROJECT
        self.dataset_map = dict(dataset_map or self.DEFAULT_DATASET_MAP)
        self.location = location
        self._verify = verify_utc
        self._client = None
        self._dialects: Dict[str, Any] = {}
        self._cache: Dict[Tuple[str, str], Tuple[str, Any]] = {}
        self.cache_hits = 0
        self.queries_run = 0
        self.bytes_billed = 0
        # Pin the process to UTC before anything renders a datetime. BigQuery hands back
        # tz-aware UTC datetimes, so this is belt-and-braces — but the cost is one env var
        # and the failure it prevents (a silent one-hour shift across a month boundary)
        # is invisible in the output.
        if os.environ.get("TZ") != "UTC":
            os.environ["TZ"] = "UTC"
            try:
                import time as _time

                _time.tzset()
            except AttributeError:  # pragma: no cover — Windows has no tzset
                pass

    # --- connection -------------------------------------------------------------------
    def _con(self):
        if self._client is None:
            from google.cloud import bigquery  # lazy: --backend duckdb needs no gcloud

            self._client = bigquery.Client(project=self.project)
            if self._verify:
                self._verify_utc()
        return self._client

    def _verify_utc(self) -> None:
        """Fail loudly if the server is not truncating in UTC.

        A wrong zone here does not raise anywhere — it just moves boundary rows into the
        neighbouring month and shows up in the agreement report as a data disagreement
        that would then be triaged as a semantic difference. Checking it costs one query.
        """
        probe = (
            "SELECT "
            "  TIMESTAMP_TRUNC(TIMESTAMP '2024-05-01 00:00:00', MONTH) AS m,"
            "  DATE(TIMESTAMP '2024-05-01 00:00:00') AS d,"
            "  DATE_TRUNC(DATE_ADD(DATE(TIMESTAMP '2024-02-01 00:00:00'),"
            "                      INTERVAL 11 MONTH), YEAR) AS fy"
        )
        row = list(self._client.query(probe).result())[0]
        m, d, fy = row[0], row[1], row[2]
        bad = []
        if m.utcoffset() is None or m.utcoffset().total_seconds() != 0 or m.strftime(
                "%Y-%m-%d %H:%M:%S") != "2024-05-01 00:00:00":
            bad.append(f"TIMESTAMP_TRUNC -> {m!r} (expected 2024-05-01 00:00:00+00:00)")
        if str(d) != "2024-05-01":
            bad.append(f"DATE(TIMESTAMP) -> {d!r} (expected 2024-05-01)")
        if str(fy) != "2025-01-01":
            bad.append(f"fiscal-year shift -> {fy!r} (expected 2025-01-01)")
        if bad:
            raise RuntimeError(
                "BigQuery is not evaluating calendar functions in UTC; the DuckDB arm's "
                "naive timestamps would not be comparable. " + "; ".join(bad))

    def _dialect(self, dataset: str):
        if dataset not in self._dialects:
            from dialects import BigQueryDialect  # compiler/ is already on sys.path

            if dataset not in self.dataset_map:
                raise KeyError(
                    f"no BigQuery dataset mapped for '{dataset}' "
                    f"(known: {', '.join(sorted(self.dataset_map)) or 'none'})")
            self._dialects[dataset] = BigQueryDialect(self.project, self.dataset_map[dataset])
        return self._dialects[dataset]

    # --- execution --------------------------------------------------------------------
    def execute(self, semantic_model: dict, plan: dict) -> Dict[str, Any]:
        from dialects import DialectError

        dataset = semantic_model["dataset"]
        try:
            comp = C.compile_plan(semantic_model, plan, self._dialect(dataset))
        except DialectError as e:
            # a warehouse-coverage gap — an ERROR, never a refusal (see class docstring)
            return {"rows": None, "sql": None, "outcome": "error",
                    "detail": f"dialect_gap: {str(e)[:280]}"}
        except KeyError as e:
            return {"rows": None, "sql": None, "outcome": "error",
                    "detail": f"dataset_map: {str(e)[:280]}"}
        if "refuse" in comp:
            # identical to the DuckDB arm: model refusals and layer refusals both land here
            # WITHOUT touching the warehouse, so a refusal can never be a backend artefact
            return {"rows": None, "sql": None, "outcome": "refusal", "detail": comp["refuse"]}
        sql = comp["sql"]
        key = (dataset, sql)
        if key in self._cache:
            self.cache_hits += 1
            state, payload = self._cache[key]
        else:
            state, payload = self._run(sql)
            self._cache[key] = (state, payload)
        if state == "error":
            return {"rows": None, "sql": sql, "outcome": "error", "detail": payload}
        return {"rows": [list(r) for r in payload], "sql": sql, "outcome": "ok", "detail": None}

    def _run(self, sql: str) -> Tuple[str, Any]:
        try:
            job = self._con().query(sql, location=self.location) if self.location \
                else self._con().query(sql)
            rows = [tuple(r.values()) for r in job.result()]
            self.queries_run += 1
            self.bytes_billed += job.total_bytes_billed or 0
            return "ok", rows
        except Exception as e:  # noqa: BLE001 — mirrors DuckDBBackend / run.py:exec_sql
            return "error", f"{type(e).__name__}: {str(e)[:280]}"

    def close(self) -> None:
        if self._client is not None:
            try:
                self._client.close()
            except Exception:  # noqa: BLE001
                pass
            self._client = None


class LookerBackend(Backend):
    """NOT IMPLEMENTED — stub. Intended mapping: plan -> Looker inline query (no SQL emitted here).

    Looker is not a SQL target; it is a second semantic layer. The point of running the
    stored plans through it is that the SQL is generated by SOMEONE ELSE'S compiler from
    an equivalent LookML model — which is what makes agreement evidence about the
    semantic contract rather than about compile.py.

    Mapping (looker_sdk 40, `sdk.run_inline_query(result_format, body: WriteQuery, ...)`):

        plan["measures"]    -> WriteQuery.fields, as "<explore>.<measure_name>"
        plan["dimensions"]  -> WriteQuery.fields, as "<explore>.<dimension_name>"
                               (fields is ONE list; dimensions come first by convention)
        plan["filters"]     -> WriteQuery.filters, a dict {"<explore>.<field>": "<expr>"}
                               where the expr is Looker filter syntax, NOT SQL:
                                 op "="  -> the bare value, or "a,b,c" for a value list
                                            produced by compile.resolve_value's vocabulary
                                            expansion (comma = OR in Looker filter syntax)
                                 op "!=" -> "-<value>"
                                 op ">"/">="/"<"/"<=" -> ">5" / ">=5" / "<5" / "<=5"
                                 date dims -> a Looker date expression ("2024" or
                                            "2024-05-01 to 2024-06-01"), not DATE '...'
        plan["order_by"]    -> WriteQuery.sorts, ["<explore>.<field> desc"] (or asc)
        plan["limit"]       -> WriteQuery.limit (as a string; -1 means unlimited)
        model / view        -> the LookML model name and explore name for the dataset;
                               supply as a {dataset: (model, explore)} map, since d1 and
                               d2 are separate explores.

    Execution: `sdk.run_inline_query("json", body)` returns a JSON string of row dicts
    keyed "<explore>.<field>"; project those back onto the plan's field order to build
    `rows` as positional tuples comparable with the SQL backends. Return sql=None (the
    generated SQL lives in Looker; `run_inline_query("sql", body)` can fetch it separately
    and is worth logging into `detail` for auditability). Refusals: keep the model-refusal
    short circuit from the Backend contract, and map a 4xx from the SDK for an unknown
    field to outcome="refusal" only if the LookML model genuinely lacks the field —
    otherwise it is outcome="error" and a model-parity bug to fix, not a refusal.

    Prerequisite, and the honest cost of this backend: a LookML model for d1/d2 whose
    measures and dimensions are name-for-name equivalent to semantic_models/*.yaml,
    including the certified filters (orders.status IN (3,4)) and the order-grain vs
    line-grain split. Any parity gap there invalidates the agreement claim, so that
    model must be generated from the same YAML, not hand-written. A draft translation is
    being assembled under lookml/ — as of this writing it is marked DRAFT/UNVALIDATED,
    has never been parsed by a Looker instance, and its BigQuery target is a placeholder.
    Wiring this backend up before that model is validated would manufacture agreement
    rather than measure it.
    """

    id = "looker"

    def __init__(self, base_url: Optional[str] = None,
                 explore_map: Optional[Dict[str, Tuple[str, str]]] = None) -> None:
        self.base_url = base_url
        self.explore_map = explore_map or {}

    def execute(self, semantic_model: dict, plan: dict) -> Dict[str, Any]:
        raise NotImplementedError(
            "LookerBackend is a stub: the plan -> WriteQuery translation, the LookML parity "
            "model for d1/d2, and the run_inline_query execution path are not implemented yet. "
            "See the class docstring for the intended mapping."
        )


BACKENDS = {"duckdb": DuckDBBackend, "bq": BigQueryBackend, "looker": LookerBackend}


def make_backend(name: str, **kw: Any) -> Backend:
    if name not in BACKENDS:
        raise SystemExit(f"unknown backend '{name}' (choose from {', '.join(BACKENDS)})")
    return BACKENDS[name](**kw)


