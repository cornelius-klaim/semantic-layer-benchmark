#!/usr/bin/env python3
"""Load the seeded d1 warehouse into BigQuery so the LookML model can query it on Looker.

Loads warehouse/d1/*.parquet (customers, products, orders, order_items, marketing_spend) plus
the generated returns table into BigQuery dataset ${BQ_PROJECT}.${BQ_DATASET}. That dataset name
must equal the @{SCHEMA} constant in lookml/d1/manifest.lkml.

Env:  BQ_PROJECT (required), BQ_DATASET (default sgl_grounding_ladder_d1), BQ_LOCATION (default US)
Auth: GOOGLE_APPLICATION_CREDENTIALS or `gcloud auth application-default login`.
"""
import os, duckdb
from google.cloud import bigquery

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.environ["BQ_PROJECT"]
DATASET = os.environ.get("BQ_DATASET", "sgl_grounding_ladder_d1")
LOCATION = os.environ.get("BQ_LOCATION", "US")

client = bigquery.Client(project=PROJECT)
client.create_dataset(bigquery.Dataset(f"{PROJECT}.{DATASET}"), exists_ok=True)
print(f"dataset {PROJECT}.{DATASET} ready ({LOCATION})")

# returns lives only in the duckdb (generated by gen_d1_returns.py); export it to parquet first
con = duckdb.connect(os.path.join(HERE, "warehouse", "d1.duckdb"), read_only=True)
rp = os.path.join(HERE, "warehouse", "d1", "returns.parquet")
con.execute(f"COPY (SELECT * FROM returns) TO '{rp}' (FORMAT PARQUET)")

for tbl in ["customers", "products", "orders", "order_items", "marketing_spend", "returns"]:
    path = os.path.join(HERE, "warehouse", "d1", f"{tbl}.parquet")
    job = client.load_table_from_file(
        open(path, "rb"),
        f"{PROJECT}.{DATASET}.{tbl}",
        job_config=bigquery.LoadJobConfig(
            source_format=bigquery.SourceFormat.PARQUET,
            write_disposition="WRITE_TRUNCATE"),
    )
    job.result()
    n = client.get_table(f"{PROJECT}.{DATASET}.{tbl}").num_rows
    print(f"  loaded {tbl:16s} {n:>8,} rows")
print("done.")
